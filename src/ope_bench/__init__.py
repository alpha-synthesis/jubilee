"""Off-Policy Evaluation (OPE) — the Oracle Program (Horizon 8).

Estimate the value of a *target* policy from logs generated by a *behavior*
policy, without deploying.  This is the substitute for the simulator-oracle
when the oracle does not exist (real client data): the model that produced the
policy cannot also be the judge of it (the circular self-grading of
``expected_return``; Levine et al. 2020).

The whole subpackage runs on a synthetic contextual bandit whose true value is
known in closed form — so we can *grade the grader* (T-31) before trusting OPE
on real data.  Pieces:

- ``bandit``         — synthetic contextual bandit with closed-form true value (T-27)
- ``logging_policy`` — incumbent behavior policy with an ε exploration floor (T-27)
- ``estimators``     — DM / IS / DR and pluggable reward models (T-28)
- ``annotator``      — simulator as counterfactual annotator → DM⁺-IS (CANDOR, T-29)
- ``confidence``     — bootstrap confidence intervals + lower bound (T-30)
- ``sequential``     — per-decision DR for window value (Jiang & Li 2016, T-32)

References: dudik2011-doubly-robust,
jiang2016-dr-rl, su2019-dr-shrinkage, mandyam2024-candor.
"""

